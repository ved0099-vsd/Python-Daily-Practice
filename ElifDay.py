def main():
    Date = int(input("enter date between 1 to 7 : "))

    if(Date == 1 ):
        print("Monday")

    elif(Date == 2):
        print("Tuesday")

    elif(Date == 3):
        print("Wednesday")

    elif(Date == 4):
            print("Thursday")

    elif(Date == 5):
            print("Friday")

    elif(Date == 6):
            print("Saturday")

    elif(Date == 7):
            print("Sunday")

    else:
        print("Invalid input")

if __name__ == "__main__":
    main()
